"""Legibility (Q5): a cost term for the planner and simulated observers to evaluate it.

Following Dragan et al. (legible vs. predictable motion), an observer who assumes the robot moves
efficiently toward its goal infers the goal G from the motion so far, xi_{S->Q}:

    P(G | xi) ~ exp(-b [C(xi) + d(Q,G)]) / exp(-b d(S,G)),   normalised over the candidate goals.

C(xi) is common to all goals, so it cancels and the posterior depends on the current point Q only:

    log P(G* | Q) = -b (d(Q,G*) - d(S,G*)) - logsumexp_g [ -b (d(Q,g) - d(S,g)) ].

The planner's legibility cost is -log P(G* | Q) along a candidate rollout. The evaluation observers
below are *simulated* people: ``CostObserver`` uses the same family of model as the cost (with a
different temperature and noisy position observations), while ``HeadingObserver`` ignores path cost
and just extrapolates the robot's recent heading, so a result that holds for both is not just the
planner optimising its own model.
"""
from __future__ import annotations

import numpy as np


def _logsumexp(x: np.ndarray, axis: int = -1) -> np.ndarray:
    m = np.max(x, axis=axis, keepdims=True)
    return (m + np.log(np.sum(np.exp(x - m), axis=axis, keepdims=True))).squeeze(axis)


def log_prob_goal(Q, S, goals, k: int, beta: float) -> np.ndarray:
    """log P(goal k | robot at Q, started at S). Q has shape (..., 2); goals (K, 2)."""
    Q, S, goals = np.asarray(Q, float), np.asarray(S, float), np.asarray(goals, float)
    dQ = np.linalg.norm(Q[..., None, :] - goals, axis=-1)
    dS = np.linalg.norm(S - goals, axis=-1)
    score = -beta * (dQ - dS)
    return score[..., k] - _logsumexp(score)


class CostObserver:
    """Bayesian observer with a cost-based (Dragan-style) model and noisy robot-position observations."""

    def __init__(self, beta: float = 0.7, obs_noise: float = 0.3):
        self.beta, self.obs_noise = beta, obs_noise

    def posterior(self, path: np.ndarray, S, goals, rng: np.random.Generator) -> np.ndarray:
        """(N, K) posterior over goals after each point of ``path`` (N, 2)."""
        goals = np.asarray(goals, float)
        seen = path + rng.normal(0.0, self.obs_noise, path.shape)
        dQ = np.linalg.norm(seen[:, None, :] - goals, axis=-1)
        dS = np.linalg.norm(np.asarray(S, float) - goals, axis=-1)
        score = -self.beta * (dQ - dS)
        return np.exp(score - _logsumexp(score)[:, None])


class HeadingObserver:
    """Observer that extrapolates the robot's heading over the last ``window`` samples."""

    def __init__(self, kappa: float = 4.0, window: int = 10, obs_noise: float = 0.1):
        self.kappa, self.window, self.obs_noise = kappa, window, obs_noise

    def posterior(self, path: np.ndarray, S, goals, rng: np.random.Generator) -> np.ndarray:
        goals = np.asarray(goals, float)
        K, N = len(goals), len(path)
        seen = path + rng.normal(0.0, self.obs_noise, path.shape)
        out = np.full((N, K), 1.0 / K)
        for n in range(self.window, N):
            v = seen[n] - seen[n - self.window]
            sp = float(np.hypot(v[0], v[1]))
            if sp < 0.1 * self.window * 0.1:      # < 0.1 m/s over the window: no heading information
                continue
            to_g = goals - seen[n]
            cos = (to_g @ v) / (np.linalg.norm(to_g, axis=1) * sp + 1e-9)
            w = np.exp(self.kappa * cos)
            out[n] = w / w.sum()
        return out


def identification_time(post: np.ndarray, k: int, dt: float, thresh: float = 0.9) -> float:
    """First time after which P(true goal) stays >= thresh; inf if it never does."""
    ok = post[:, k] >= thresh
    if not ok[-1]:
        return float("inf")
    bad = np.where(~ok)[0]
    return float((bad[-1] + 1 if len(bad) else 0) * dt)


def _features(seen: np.ndarray, goals: np.ndarray, window: int) -> np.ndarray:
    """(N, K, 3) per-goal features after each sample: cosine of motion direction vs. direction to the goal,
    progress toward the goal over the window (m / m moved), and a constant. Zeros before one window."""
    N, K = len(seen), len(goals)
    f = np.zeros((N, K, 3))
    for n in range(window, N):
        v = seen[n] - seen[n - window]
        sp = float(np.hypot(v[0], v[1]))
        if sp < 1e-3:
            continue
        to_g = goals - seen[n]
        d_now = np.linalg.norm(to_g, axis=1)
        d_old = np.linalg.norm(goals - seen[n - window], axis=1)
        f[n, :, 0] = (to_g @ v) / (d_now * sp + 1e-9)
        f[n, :, 1] = (d_old - d_now) / sp
        f[n, :, 2] = 1.0
    return f


def _human_like_path(rng: np.random.Generator, start, goal, dt: float = 0.1, v: float = 0.9) -> np.ndarray:
    """A noisy-rational walker: heads toward the goal with a lagged, noisy heading and noisy speed.
    Deliberately not generated by the planner, the cost observer or the heading observer."""
    start, goal = np.asarray(start, float), np.asarray(goal, float)
    p = start.copy()
    th = float(np.arctan2(goal[1] - start[1], goal[0] - start[0]) + rng.normal(0, 0.3))
    path = [p.copy()]
    for _ in range(600):
        if np.linalg.norm(goal - p) < 2.0:
            break
        want = float(np.arctan2(goal[1] - p[1], goal[0] - p[0]))
        th += 0.15 * np.arctan2(np.sin(want - th), np.cos(want - th)) + rng.normal(0, 0.06)
        p = p + dt * v * rng.uniform(0.7, 1.1) * np.array([np.cos(th), np.sin(th)])
        path.append(p.copy())
    return np.array(path)


class LearnedObserver:
    """Third, independent observer: a conditional-logit goal classifier learned from synthetic noisy-rational
    walkers (features: motion-vs-goal direction and progress toward each goal). It shares neither the planner's
    cost model (CostObserver) nor a hand-set heading likelihood (HeadingObserver)."""

    _cache: dict = {}

    def __init__(self, window: int = 10, obs_noise: float = 0.1, n_train: int = 300, seed: int = 12345):
        self.window, self.obs_noise = window, obs_noise
        key = (window, obs_noise, n_train, seed)
        if key not in LearnedObserver._cache:
            LearnedObserver._cache[key] = self._train(n_train, seed)
        self.theta = LearnedObserver._cache[key]

    def _train(self, n_train: int, seed: int) -> np.ndarray:
        rng = np.random.default_rng(seed)
        X, y = [], []
        for _ in range(n_train):
            K = int(rng.integers(2, 4))
            start = np.array([20.0, 50.0]) + rng.normal(0, 2, 2)
            bearing, side = rng.uniform(-0.4, 0.4), (1 if rng.random() < 0.5 else -1)
            goals = [start + 22 * rng.uniform(0.85, 1.15) * np.array([np.cos(bearing), np.sin(bearing)])]
            for _k in range(K - 1):
                off = np.deg2rad(rng.uniform(15, 45)) * side
                goals.append(start + 22 * rng.uniform(0.85, 1.15) * np.array([np.cos(bearing + off), np.sin(bearing + off)]))
            goals = np.array(goals)
            true = int(rng.integers(K))
            path = _human_like_path(rng, start, goals[true])
            seen = path + rng.normal(0, self.obs_noise, path.shape)
            F = _features(seen, goals, self.window)
            for n in range(self.window, len(path), 3):
                X.append(F[n])
                y.append(true)
        Kmax = max(len(x) for x in X)
        Xp = np.zeros((len(X), Kmax, 3))
        mask = np.zeros((len(X), Kmax), bool)
        for i, x in enumerate(X):
            Xp[i, :len(x)] = x
            mask[i, :len(x)] = True
        y = np.array(y)
        theta = np.zeros(3)
        for _ in range(400):
            s = np.where(mask, Xp @ theta, -np.inf)
            s -= s.max(1, keepdims=True)
            P = np.exp(s)
            P /= P.sum(1, keepdims=True)
            grad = Xp[np.arange(len(y)), y].sum(0) - np.einsum("nk,nkf->f", P, Xp)
            theta += 0.5 * grad / len(y)
        return theta

    def posterior(self, path: np.ndarray, S, goals, rng: np.random.Generator) -> np.ndarray:
        goals = np.asarray(goals, float)
        seen = path + rng.normal(0.0, self.obs_noise, path.shape)
        F = _features(seen, goals, self.window)
        s = F @ self.theta
        s -= s.max(1, keepdims=True)
        P = np.exp(s)
        P /= P.sum(1, keepdims=True)
        P[: self.window] = 1.0 / len(goals)
        return P
